// Builds dist/brc-vault.html: one self-contained file with all code inlined.
import { build, transform } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';

const result = await build({
  entryPoints: ['src/app.js'],
  bundle: true,
  format: 'iife',
  target: ['es2020'],
  minify: false, // kept readable on purpose so anyone can review it
  legalComments: 'inline',
  write: false,
  plugins: [{
    // jsQR ships as a large unminified file; minify just that library so the
    // page stays small, while our own code stays readable.
    name: 'minify-jsqr',
    setup(b) {
      b.onLoad({ filter: /jsqr[\\/]dist[\\/]jsQR\.js$/ }, async (args) => ({
        contents: (await transform(readFileSync(args.path, 'utf8'), { minify: true, format: 'cjs' })).code,
        loader: 'js',
      }));
    },
  }],
});
let js = result.outputFiles[0].text;
if (/<\/script/i.test(js)) js = js.replace(/<\/script/gi, '<\\/script');

const firstLine = (p) => readFileSync(p, 'utf8').split('\n').find((l) => /copyright/i.test(l))?.replace(/^\s*\/\/\s*/, '').trim();
const notices = [
  ['@noble/ed25519', 'node_modules/@noble/ed25519/LICENSE'],
  ['@noble/hashes', 'node_modules/@noble/hashes/LICENSE'],
  ['qrcode-generator', 'node_modules/qrcode-generator/qrcode.js'],
].map(([name, path]) => ` * ${name} (MIT) — ${firstLine(path) || 'see project license'}`).join('\n')
  + '\n * jsQR (Apache License 2.0) — by Cosmo Wolfe and contributors, github.com/cozmo/jsQR; see third-party/jsQR-LICENSE';

const header = `/*!
 * BRC Vault — offline backups for BrowserCoin wallets. MIT License.
 * Includes these open-source libraries:
${notices}
 */
`;

// Fonts are embedded so the page looks the same offline. Geist and Geist Mono
// are © Vercel, SIL Open Font License 1.1 (see fonts/OFL-Geist.txt); subset to Latin.
const font = (family, file) => `@font-face { font-family: "${family}"; font-style: normal; font-weight: 100 900; font-display: swap; src: url(data:font/woff2;base64,${readFileSync(file).toString('base64')}) format("woff2"); }`;
const fonts = [
  '/* Geist and Geist Mono © Vercel, SIL Open Font License 1.1 */',
  font('Geist', 'fonts/Geist-Variable.subset.woff2'),
  font('Geist Mono', 'fonts/GeistMono-Variable.subset.woff2'),
].join('\n');

// Logo artwork comes from brand/ (generated by brand/make_logo.py).
const markInner = readFileSync('brand/mark-inner.txt', 'utf8').trim();
// The same mark, with its parts named so the lock moment can animate them.
const markMoment = markInner
  .replace('<rect ', '<rect class="lm-box" ')
  .replace('<path ', '<path class="lm-v" ')
  .replace('<circle ', '<circle class="lm-dot" ');
const markView = readFileSync('brand/brc-vault-mark.svg', 'utf8').match(/viewBox="([^"]+)"/)[1];
const favicon = 'data:image/svg+xml,' + encodeURIComponent(readFileSync('brand/brc-vault-mark-white.svg', 'utf8').trim());

let html = readFileSync('src/index.html', 'utf8')
  .replace('/*__MARK__*/', () => markInner)
  .replaceAll('/*__MARK_MOMENT__*/', () => markMoment)
  .replaceAll('/*__MARK_VIEW__*/', () => markView)
  .replace('/*__FAVICON__*/', () => favicon)
  .replace('/*__FONTS__*/', () => fonts)
  .replace('/*__APP__*/', () => header + js);
// Lock the page down to exactly this one script: no other script can run, not even injected markup.
const scriptBody = html.match(/<script>([\s\S]*?)<\/script>/)[1];
const scriptHash = createHash('sha256').update(scriptBody, 'utf8').digest('base64');
html = html.replace("'__SCRIPT_HASH__'", `'sha256-${scriptHash}'`);
// The build label comes from the code itself, not the clock, so anyone who
// rebuilds from the same source gets a byte-for-byte identical file and hash.
const buildId = createHash('sha256').update(scriptBody, 'utf8').digest('hex').slice(0, 8);
html = html.replace('/*__BUILD__*/', () => buildId);
if ((html.match(/<script/g) || []).length !== 1) throw new Error('Expected exactly one script tag');

mkdirSync('dist', { recursive: true });
writeFileSync('dist/brc-vault.html', html);
// The same file is served by GitHub Pages from docs/.
mkdirSync('docs', { recursive: true });
writeFileSync('docs/index.html', html);
writeFileSync('docs/brc-vault.html', html);
const sha = createHash('sha256').update(html).digest('hex');
writeFileSync('dist/SHA256.txt', `${sha}  brc-vault.html\n`);
console.log(`dist/brc-vault.html ${(html.length / 1024).toFixed(1)} KB  sha256 ${sha}`);
